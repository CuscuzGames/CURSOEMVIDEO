# Balde de Tinta

a = int(input("Qual a altura da parede? "))
b = int(input("Qual a largura da parede? "))
t = a * b
l = t / 2

print(f"\nSe a Altura é {a}")
print(f"E se a Largura é {b}")
print(f"Então tem uma área de {t} metros quadrados")
print(f"Será necessario {l} litros de tinta para pintala.")
